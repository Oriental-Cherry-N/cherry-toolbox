export type Locale = keyof typeof TRANSLATIONS;
export type TranslationKey = keyof (typeof TRANSLATIONS)['en'];

export const locale: Locale = (() => {
  const language = navigator.language.toLocaleLowerCase('en-US');
  if (language.startsWith('zh')) return 'zh';
  if (language.startsWith('fr')) return 'fr';
  return 'en';
})();

export function t(
  key: TranslationKey,
  values: Record<string, string> = {},
): string {
  let message: string = TRANSLATIONS[locale][key];
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, value);
  }
  return message;
}

export function applyTranslations(): void {
  document.documentElement.lang = locale === 'zh' ? 'zh-CN' : locale;
  for (const element of document.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = element.dataset.i18n as TranslationKey | undefined;
    if (key && key in TRANSLATIONS.en) element.textContent = t(key);
  }
  for (const element of document.querySelectorAll<HTMLElement>(
    '[data-i18n-placeholder]',
  )) {
    const key = element.dataset.i18nPlaceholder as TranslationKey | undefined;
    if (key && key in TRANSLATIONS.en) element.setAttribute('placeholder', t(key));
  }
}
